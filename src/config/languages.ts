export function detectScriptDirection(text: string, fallback: 'ltr' | 'rtl' = 'ltr'): 'ltr' | 'rtl' {
  // Check for Arabic, Urdu, Persian, Pashto, Sindhi Unicode blocks
  const rtlRegex = /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/;
  if (rtlRegex.test(text)) {
    return 'rtl';
  }
  return fallback;
}
